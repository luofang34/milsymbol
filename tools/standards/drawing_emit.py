from drawing_config import WORK, ROOT, SOURCES
import json
import drawing_paths as paths
from pathlib import Path
m=json.load(open(str(WORK / 'matched.json')));icons=json.load(open(str(WORK / 'icons.json')))
icons.update(json.load(open(str(WORK / 'metoc-icons.json'))))
icons.update(json.load(open(WORK / 'controls-icons.json')))
q=lambda s:json.dumps(s,ensure_ascii=False)
kindmap={'entity':'Entity','m1':'Modifier1','m2':'Modifier2','common_m1':'Modifier1','common_m2':'Modifier2'}
ordered=[]
for name,rows in m.items():
 for r in rows:
  key=name+' '+f"{r['symbol_set']} {r['kind']} {r['code']}"
  k=kindmap[r['kind']];code=r['code'] if r['kind'] not in ['m1','m2'] else '0'+r['code']
  ordered.append(((15 if name=='mil2525e1' else 16,r['symbol_set'],['Entity','Modifier1','Modifier2'].index(k),code),r,name,k,key))
# APP-6 Table A-4 explicitly delegates these sets to US symbology.
for key,r,name,kind,source_key in list(ordered):
 if key[0]==15 and key[1] in ['06','45','46','47','50','51','52','53','54']:
  ordered.append(((16,*key[1:]),r,name,kind,source_key))
ordered.sort(key=lambda v:v[0]);geoms=[];entries=[];graphic_indices={}
seen=set()
for (v,ss,_,code),r,name,kind,key in ordered:
 if (v,ss,kind,code) in seen:continue
 seen.add((v,ss,kind,code))
 geom='None'
 if key in icons:
  if key not in graphic_indices:
   graphic_indices[key]=len(geoms);geoms.append(icons[key] | {'document':name})
  geom=f'Some({graphic_indices[key]})' 
 scope=r['scope'].title()
 assert scope in ['Point','Empty','Hierarchy','Multipoint'], (key,scope)
 entries.append(f'    Entry {{ version: {v}, symbol_set: {q(ss)}, kind: CodeKind::{kind}, code: {q(code)}, name: {q(r["name"])}, scope: Scope::{scope}, source: Source {{ document: {q(name)}, page: {r["page"]}, table: {q(r["table"])} }}, graphic: {geom} }},')
s='// @generated by tools/standards; source PDFs pinned in tools/standards/pin.json.\nuse crate::catalog::standards::{Entry, CodeKind, Scope, Source};\nuse crate::compose::icon::standards::{Graphic, GraphicPath, GraphicInput, Layout};\n\npub(crate) static ENTRIES: &[Entry] = &[\n'+'\n'.join(entries)+'\n];\n\npub(crate) static GRAPHICS: &[Graphic] = &[\n'
for g in geoms:
 source=g['source']
 boxes=[paths.bounds(p['d'],paths.IDENTITY) for p in g['paths']]
 bounds=[min(b[0] for b in boxes),min(b[1] for b in boxes),max(b[2] for b in boxes),max(b[3] for b in boxes)] if boxes else [100.,100.,100.,100.]
 bounds=[round(v,6) for v in bounds]
 spec=g.get('input');inp='None'
 if spec:
  color=g['paths'][0]['fill'] if g['paths'] else 'gray'
  inp=f'Some(GraphicInput {{ field: {q(spec["field"])}, x: {float(spec["x"])}, y: {float(spec["y"])}, size: {float(spec["size"])}, bold: {str(spec.get("weight")=="bold").lower()}, subscript_decimal: {str(spec.get("subscript_decimal",False)).lower()}, color: {q(color)} }})'
 s+=f'    Graphic {{ layout: Layout::{g.get("layout","Fixed")}, bbox: {bounds}, source: Source {{ document: {q(g["document"])}, page: {source["printed"]}, table: {q(source["table"])} }}, input: {inp}, paths: &[\n'
 for p in g['paths']:
  paint=lambda v:'None' if v is None or v=='none' else f'Some({q(v)})'
  s+=f'        GraphicPath {{ d: {q(p["d"])}, fill: {paint(p["fill"])}, stroke: {paint(p["stroke"])}, width: {float(p["width"])} }},\n'
 s+='    ] },\n'
s+='];\n'
for name,g in json.load(open(str(WORK / 'context-icons.json'))).items():
 s+=f'\npub(crate) static {name.upper()}: &[GraphicPath] = &[\n'
 for p in g['paths']:
  s+=f'    GraphicPath {{ d: {q(p["d"])}, fill: Some({q(p["fill"])}), stroke: None, width: 0.0 }},\n'
 s+='];\n'
Path('src/generated/standards.rs').write_text(s)
# Explicitly distinguish unavailable multipoint rendering from missing single-point data.
lines=['document\tsymbol_set\tkind\tcode\tscope\tdrawing_page\tdrawing_table']
for document,rows in m.items():
 for row in rows:
  d=row.get('drawing') or {}
  lines.append('\t'.join([document,row['symbol_set'],row['kind'],row['code'],row['scope'],str(d.get('printed','')),d.get('table','')]))
Path('tests/data/standards/scope.tsv').write_text('\n'.join(lines)+'\n')

leadership=json.loads((WORK / 'leadership.json').read_text())
s+='\npub(crate) static LEADERSHIP: &[(&str, [[f64; 2]; 3])] = &[\n'
for row in leadership:
 s+=f'    ({q(row["affiliation"])}, {row["points"]}),\n'
s+='];\n'
Path('src/generated/standards.rs').write_text(s)
